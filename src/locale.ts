export function resolveLocale(lang?: string | null): LocaleStrings {
  const normalized = (lang || '').trim().toLowerCase();
  if (
    normalized === 'zh-tw' ||
    normalized === 'zh-hk' ||
    normalized.startsWith('zh-hant') ||
    normalized.startsWith('zh-tw') ||
    normalized.startsWith('zh-hk')
  ) {
    return LOCALE['zh-tw'];
  }
  if (normalized.startsWith('zh')) {
    return LOCALE.zh;
  }
  if (normalized.startsWith('ja')) {
    return LOCALE.ja;
  }
  if (normalized.startsWith('ko')) {
    return LOCALE.ko;
  }
  if (normalized.startsWith('fr')) {
    return LOCALE.fr;
  }
  if (normalized.startsWith('de')) {
    return LOCALE.de;
  }
  if (normalized.startsWith('es')) {
    return LOCALE.es;
  }
  if (normalized.startsWith('ru')) {
    return LOCALE.ru;
  }
  if (normalized.startsWith('en')) {
    return LOCALE.en;
  }
  if (lang && SUPPORTED_DISPLAY_LANGUAGES.includes(lang as DisplayLanguage)) {
    return LOCALE[lang as DisplayLanguage];
  }
  return LOCALE[DEFAULT_DISPLAY_LANGUAGE];
}

export function getLocale(lang: DisplayLanguage): LocaleStrings {
  return LOCALE[lang] || LOCALE[DEFAULT_DISPLAY_LANGUAGE];
}

/** Look up a localized string or call a format function by key. */
export function localize(lang: string | DisplayLanguage, key: keyof LocaleStrings | string, ...args: unknown[]): string {
  const locale = resolveLocale(lang);
  const entry = (locale as unknown as Record<string, unknown>)[key];
  if (typeof entry === 'function') {
    return (entry as (...a: unknown[]) => string)(...args);
  }
  if (typeof entry === 'string') {
    return entry;
  }
  return String(key);
}
