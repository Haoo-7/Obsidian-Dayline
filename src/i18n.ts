/** Order of the settings dropdown: system first, then every supported language. */
export const DISPLAY_LANGUAGE_OPTIONS: DisplayLanguageSetting[] = ['system', ...SUPPORTED_DISPLAY_LANGUAGES];

/** Language names are shown in their own script, so the same key list serves every locale. */
export const DISPLAY_LANGUAGE_LABEL_KEYS: Record<DisplayLanguageSetting, string> = {
  system: 'system',
  en: 'english',
  zh: 'chinese',
  'zh-tw': 'traditionalChinese',
  ja: 'japanese',
  ko: 'korean',
  fr: 'french',
  de: 'german',
  es: 'spanish',
  ru: 'russian',
};

export const LOCALE_TAGS: Record<DisplayLanguage, string> = {
  zh: 'zh-CN',
  'zh-tw': 'zh-TW',
  en: 'en-US',
  ja: 'ja-JP',
  ko: 'ko-KR',
  fr: 'fr-FR',
  de: 'de-DE',
  es: 'es-ES',
  ru: 'ru-RU',
};

function systemLocale(): string | undefined {
  const navigatorLocale = typeof navigator !== 'undefined' ? navigator.language : undefined;
  if (navigatorLocale) return navigatorLocale;
  try {
    return new Intl.DateTimeFormat().resolvedOptions().locale;
  } catch {
    return undefined;
  }
}

function resolveSystemDisplayLanguage(): DisplayLanguage {
  const locale = systemLocale()?.toLowerCase() || '';
  if (
    locale === 'zh-tw' ||
    locale === 'zh-hk' ||
    locale.startsWith('zh-hant') ||
    locale.startsWith('zh-tw') ||
    locale.startsWith('zh-hk')
  ) {
    return 'zh-tw';
  }
  if (locale.startsWith('zh')) return 'zh';
  if (locale.startsWith('ja')) return 'ja';
  if (locale.startsWith('ko')) return 'ko';
  if (locale.startsWith('fr')) return 'fr';
  if (locale.startsWith('de')) return 'de';
  if (locale.startsWith('es')) return 'es';
  if (locale.startsWith('ru')) return 'ru';
  if (locale.startsWith('en')) return 'en';
  return locale ? 'en' : 'zh';
}

export function normalizeDisplayLanguageSetting(settings: LanguageSettings = {}): DisplayLanguageSetting {
  if (settings.displayLanguage === 'system') return 'system';
  if (settings.displayLanguage && SUPPORTED_DISPLAY_LANGUAGES.includes(settings.displayLanguage as DisplayLanguage)) {
    return settings.displayLanguage as DisplayLanguage;
  }
  if (settings.weatherLanguage && SUPPORTED_DISPLAY_LANGUAGES.includes(settings.weatherLanguage as DisplayLanguage)) {
    return settings.weatherLanguage as DisplayLanguage;
  }
  return settings.weatherLanguage === 'en' ? 'en' : 'zh';
}

export function getDisplayLanguage(settings: LanguageSettings = {}): DisplayLanguage {
  const language = settings.displayLanguage || settings.weatherLanguage;
  if (language === 'system') return resolveSystemDisplayLanguage();
  if (language && SUPPORTED_DISPLAY_LANGUAGES.includes(language as DisplayLanguage)) {
    return language as DisplayLanguage;
  }
  return language === 'en' ? 'en' : 'zh';
}

/**
 * CLDR plural categories, mapped to the suffix a count label uses. Keys without
 * the suffix are the `other` form, which every catalogue must define; the other
 * categories are optional per language and fall back to `other`.
 */
const PLURAL_KEY_SUFFIX: Record<Intl.LDMLPluralRule, string> = {
  zero: 'Zero',
  one: 'One',
  two: 'Two',
  few: 'Few',
  many: 'Many',
  other: '',
};

/** Plural category for a count, falling back to the one-vs-many split. */
function pluralCategory(lang: DisplayLanguage, count: number): Intl.LDMLPluralRule {
  try {
    return new Intl.PluralRules(LOCALE_TAGS[lang] || LOCALE_TAGS.en).select(count);
  } catch {
    // Older embedded Chromium may not expose Intl.PluralRules.
    return count === 1 ? 'one' : 'other';
  }
}

/**
 * Look up a catalogue string with CLDR plural selection. A key such as
 * `calendarEntryCount` with a numeric `count` resolves to
 * `calendarEntryCountOne` / `calendarEntryCountFew` / `calendarEntryCountMany`
 * when the language defines that category, and to the base key otherwise. This
 * is what keeps Russian from rendering "2 записей": the one-vs-other split
 * cannot express its `few` and `many` forms.
 */
function selectString(lang: DisplayLanguage, key: string, values: Record<string, unknown>): string {
  const count = values.count;
  if (typeof count === 'number' && Number.isFinite(count)) {
    const suffixed = `${key}${PLURAL_KEY_SUFFIX[pluralCategory(lang, count)]}`;
    const plural = STRINGS[lang]?.[suffixed] ?? STRINGS.en[suffixed];
    if (plural !== undefined) return plural;
  }
  return STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
}

export function t(settings: LanguageSettings, key: string, values: Record<string, unknown> = {}): string {
  const lang = getDisplayLanguage(settings);
  let value = selectString(lang, key, values);
  // `replaceAll`: a template may use the same placeholder more than once.
  for (const [name, replacement] of Object.entries(values)) value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}

export function moodLabelKey(score: MoodScore): string {
  return score === -2 ? 'veryLow' : score === -1 ? 'low' : score === 0 ? 'neutral' : score === 1 ? 'good' : 'veryGood';
}

export function moodLabel(settings: LanguageSettings, score: MoodScore): string {
  return t(settings, moodLabelKey(score));
}

export function feelingLabel(settings: LanguageSettings, id: string): string {
  return t(settings, id);
}

export function formatJournalDate(date: string, settings: LanguageSettings): string {
  const value = new Date(`${date}T12:00:00`);
  const lang = getDisplayLanguage(settings);
  if (lang === 'zh') {
    const parts = new Intl.DateTimeFormat('zh-CN', { month: 'numeric', day: 'numeric', weekday: 'short' }).formatToParts(value);
    const month = parts.find((part) => part.type === 'month')?.value ?? '';
    const day = parts.find((part) => part.type === 'day')?.value ?? '';
    const weekday = (parts.find((part) => part.type === 'weekday')?.value ?? '').replace('周', '');
    return `${month}月${day}日 周${weekday}`;
  }
  if (lang === 'zh-tw') {
    const parts = new Intl.DateTimeFormat('zh-TW', { month: 'numeric', day: 'numeric', weekday: 'short' }).formatToParts(value);
    const month = parts.find((part) => part.type === 'month')?.value ?? '';
    const day = parts.find((part) => part.type === 'day')?.value ?? '';
    const weekday = (parts.find((part) => part.type === 'weekday')?.value ?? '').replace(/^(?:星期|週)/, '');
    return `${month}月${day}日 週${weekday}`;
  }
  const localeTag = LOCALE_TAGS[lang] || LOCALE_TAGS.en;
  return new Intl.DateTimeFormat(localeTag, { month: 'short', day: 'numeric', weekday: 'short' }).format(value);
}

/**
 * A UTC date for a possibly two-digit year.
 *
 * `Date.UTC(5, 0, 1)` does not build year 5: the Date constructor maps years
 * 0–99 onto 1900–1999, so it silently returns 1905. The jump panel accepts
 * years 1–99, which made `formatCalendarMonth` and `getCalendarGridOffset`
 * disagree by a day or two. Building on a fixed base year and then setting the
 * real year keeps the mapping linear for every input.
 */
function utcDateOf(year: number, monthIndex: number, day: number): Date {
  const date = new Date(Date.UTC(2000, monthIndex, day));
  date.setUTCFullYear(year);
  return date;
}

export function formatCalendarMonth(
  year: number,
  month: number,
  settings: LanguageSettings,
): string {
  const lang = getDisplayLanguage(settings);
  const locale = LOCALE_TAGS[lang] || LOCALE_TAGS.en;
  return new Intl.DateTimeFormat(locale, {
    year: 'numeric',
    month: 'long',
    timeZone: 'UTC',
  }).format(utcDateOf(year, month - 1, 1));
}

export function resolveWeekStart(settings: LanguageSettings = {}): 0 | 1 {
  if (settings.weekStart === 'sunday') return 0;
  if (settings.weekStart === 'monday') return 1;
  if (settings.weekStart !== 'system') return 0;

  const locale = systemLocale();
  try {
    const localeWithWeekInfo = locale ? new Intl.Locale(locale) as Intl.Locale & { weekInfo?: { firstDay?: number } } : null;
    const firstDay = localeWithWeekInfo?.weekInfo?.firstDay;
    if (firstDay === 1) return 1;
    if (firstDay === 7) return 0;
  } catch {
    // Older embedded Chromium versions may not expose Intl.Locale.weekInfo.
  }

  const region = locale?.match(/[-_]([A-Z]{2}|\d{3})$/i)?.[1]?.toUpperCase();
  return region && ['US', 'CA', 'AU', 'NZ', 'JP', 'PH', 'TW', 'HK', 'IL', 'MX'].includes(region) ? 0 : 1;
}

export function getCalendarGridOffset(year: number, monthIndex: number, settings: LanguageSettings = {}): number {
  const rawSundayIndex = utcDateOf(year, monthIndex, 1).getUTCDay();
  return (rawSundayIndex - resolveWeekStart(settings) + 7) % 7;
}

export function getCalendarWeekdays(settings: LanguageSettings = {}): string[] {
  const lang = getDisplayLanguage(settings);
  const locale = LOCALE_TAGS[lang] || LOCALE_TAGS.en;
  const formatter = new Intl.DateTimeFormat(locale, { weekday: 'short', timeZone: 'UTC' });
  const sundayFirst = Array.from({ length: 7 }, (_, index) => {
    const label = formatter.format(new Date(Date.UTC(2021, 7, 1 + index)));
    return (locale === 'zh-CN' || locale === 'zh-TW') ? label.replace(/^(?:星期|周|週)/, '') : label;
  });
  const start = resolveWeekStart(settings);
  return sundayFirst.slice(start).concat(sundayFirst.slice(0, start));
}
